#!/usr/bin/env python3
"""Summarize ViPE per-window vs clip-once comparison runs.

Reads outputs/window_mode_compare/*/summary.csv generated by
compare_vipe_window_modes.py and writes aggregate CSV/Markdown plus PNG charts.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import re
import subprocess
from collections import defaultdict
from pathlib import Path
from typing import Any

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

METRICS = [
    ("vipe_elapsed_s", "ViPE elapsed", "seconds", True),
    ("ate_rmse_sim3", "ATE Sim3", "RMSE", True),
    ("rpe_rot_deg_mean_sim3", "RPE rot", "deg", True),
    ("axis_ate_rmse", "Axis ATE", "RMSE", True),
    ("fx_rel_mean", "fx rel", "relative", True),
]

EXP_RE = re.compile(r"^(?P<stem>.+)_ws(?P<window_size>\d+)_stride(?P<stride>\d+)_start(?P<start>\d+)$")


def parse_float(value: str) -> float | None:
    if value == "" or value is None:
        return None
    try:
        x = float(value)
    except ValueError:
        return None
    return x if math.isfinite(x) else None


def read_rows(summary_csv: Path) -> list[dict[str, Any]]:
    exp = summary_csv.parent.name
    match = EXP_RE.match(exp)
    meta = match.groupdict() if match else {"stem": exp, "window_size": "", "stride": "", "start": ""}
    rows: list[dict[str, Any]] = []
    with summary_csv.open() as f:
        for row in csv.DictReader(f):
            out: dict[str, Any] = dict(row)
            out.update(meta)
            out["experiment"] = exp
            out["summary_csv"] = str(summary_csv)
            for key in ["start_frame", "end_frame", "num_frames"]:
                out[key] = int(out[key]) if out.get(key) else None
            for key, _, _, _ in METRICS:
                out[key] = parse_float(out.get(key, ""))
            rows.append(out)
    return rows


def mean(values: list[float | None]) -> float | None:
    xs = [x for x in values if x is not None]
    return float(np.mean(xs)) if xs else None


def pct_change(old: float | None, new: float | None) -> float | None:
    if old is None or new is None or abs(old) < 1e-12:
        return None
    return (old - new) / old * 100.0


def fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def pick_mode_rows(by_mode: dict[str, list[dict[str, Any]]], names: tuple[str, ...]) -> tuple[str, list[dict[str, Any]]]:
    for name in names:
        rows = by_mode.get(name, [])
        if rows:
            return name, rows
    return names[0], []


def ffprobe_video_info(path: Path) -> dict[str, Any]:
    result = subprocess.run(
        [
            "ffprobe", "-v", "error",
            "-select_streams", "v:0",
            "-show_entries", "stream=width,height,avg_frame_rate,nb_frames,duration",
            "-of", "json",
            str(path),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    stream = json.loads(result.stdout)["streams"][0]
    return {
        "input_mp4": str(path),
        "input_width": int(stream.get("width") or 0),
        "input_height": int(stream.get("height") or 0),
        "input_fps": stream.get("avg_frame_rate", ""),
        "input_frames": int(stream["nb_frames"]) if str(stream.get("nb_frames", "")).isdigit() else None,
        "input_duration_s": float(stream["duration"]) if stream.get("duration") else None,
    }


def summarize_experiment(rows: list[dict[str, Any]], gt_root: Path | None = None) -> dict[str, Any]:
    by_mode: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_mode[row["mode"]].append(row)
    per_mode, per = pick_mode_rows(by_mode, ("resident_per_window", "per_window"))
    clip_mode, clip = pick_mode_rows(by_mode, ("resident_clip_once_then_slice", "clip_once"))
    if not per or not clip:
        raise ValueError(f"missing comparable A/B modes in {rows[0]['experiment']}: {sorted(by_mode)}")

    summary: dict[str, Any] = {
        "experiment": rows[0]["experiment"],
        "stem": rows[0]["stem"],
        "window_size": rows[0]["window_size"],
        "stride": rows[0]["stride"],
        "start": rows[0]["start"],
        "windows": len(per),
        "per_window_mode": per_mode,
        "clip_once_mode": clip_mode,
    }
    if gt_root is not None:
        mp4 = gt_root / f"{rows[0]['stem']}_aligned.mp4"
        if mp4.exists():
            summary.update(ffprobe_video_info(mp4))
    per_elapsed = sum(float(r["vipe_elapsed_s"] or 0.0) for r in per)
    clip_elapsed_values = [r["vipe_elapsed_s"] for r in clip if r["vipe_elapsed_s"] is not None]
    clip_elapsed = float(clip_elapsed_values[0]) if clip_elapsed_values else None
    summary["per_window_vipe_elapsed_s"] = per_elapsed
    summary["clip_once_vipe_elapsed_s"] = clip_elapsed
    summary["time_saved_s"] = per_elapsed - clip_elapsed if clip_elapsed is not None else None
    summary["time_saved_pct"] = pct_change(per_elapsed, clip_elapsed)

    for key, _, _, _ in METRICS[1:]:
        per_mean = mean([r[key] for r in per])
        clip_mean = mean([r[key] for r in clip])
        summary[f"per_window_{key}_mean"] = per_mean
        summary[f"clip_once_{key}_mean"] = clip_mean
        summary[f"{key}_reduction_pct"] = pct_change(per_mean, clip_mean)
        wins = 0
        comparable = 0
        per_by_window = {r["window_id"]: r for r in per}
        for c in clip:
            p = per_by_window.get(c["window_id"])
            if p and p[key] is not None and c[key] is not None:
                comparable += 1
                wins += int(c[key] < p[key])
        summary[f"{key}_clip_once_wins"] = wins
        summary[f"{key}_comparable_windows"] = comparable
    return summary


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    keys: list[str] = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                keys.append(key)
                seen.add(key)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)


def plot_time(exps: list[dict[str, Any]], out: Path) -> None:
    labels = [e["stem"] for e in exps]
    x = np.arange(len(labels))
    width = 0.36
    per = [e["per_window_vipe_elapsed_s"] for e in exps]
    clip = [e["clip_once_vipe_elapsed_s"] for e in exps]
    fig, ax = plt.subplots(figsize=(max(9, len(labels) * 0.8), 5))
    ax.bar(x - width / 2, per, width, label="per_window")
    ax.bar(x + width / 2, clip, width, label="clip_once")
    ax.set_ylabel("ViPE elapsed seconds")
    ax.set_title("ViPE runtime by video")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.legend()
    ax.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(out, dpi=140)
    plt.close(fig)


def plot_pct(exps: list[dict[str, Any]], key: str, title: str, out: Path) -> None:
    labels = [e["stem"] for e in exps]
    values = [e.get(key) for e in exps]
    fig, ax = plt.subplots(figsize=(max(9, len(labels) * 0.8), 4.8))
    colors = ["#2ca02c" if (v or 0) >= 0 else "#d62728" for v in values]
    ax.bar(np.arange(len(labels)), [0 if v is None else v for v in values], color=colors)
    ax.axhline(0, color="#333333", linewidth=0.8)
    ax.set_ylabel("clip_once improvement vs per_window (%)")
    ax.set_title(title)
    ax.set_xticks(np.arange(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(out, dpi=140)
    plt.close(fig)


def plot_metric_values(exps: list[dict[str, Any]], metric: str, title: str, out: Path) -> None:
    labels = [e["stem"] for e in exps]
    x = np.arange(len(labels))
    width = 0.36
    per = [e.get(f"per_window_{metric}_mean") for e in exps]
    clip = [e.get(f"clip_once_{metric}_mean") for e in exps]
    fig, ax = plt.subplots(figsize=(max(9, len(labels) * 0.8), 5))
    ax.bar(x - width / 2, [np.nan if v is None else v for v in per], width, label="per_window")
    ax.bar(x + width / 2, [np.nan if v is None else v for v in clip], width, label="clip_once")
    ax.set_ylabel("mean value, lower is better")
    ax.set_title(title)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.legend()
    ax.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(out, dpi=140)
    plt.close(fig)


def write_markdown(path: Path, exps: list[dict[str, Any]], images: list[Path]) -> None:
    total_per = sum(e["per_window_vipe_elapsed_s"] for e in exps)
    total_clip = sum(e["clip_once_vipe_elapsed_s"] for e in exps if e["clip_once_vipe_elapsed_s"] is not None)
    total_input_duration = sum(float(e.get("input_duration_s") or 0.0) for e in exps)
    total_input_frames = sum(int(e.get("input_frames") or 0) for e in exps)
    lines = [
        "# ViPE Window Mode Aggregate Summary",
        "",
        "## Overall",
        "",
        f"- videos: {len(exps)}",
        f"- total windows: {sum(e['windows'] for e in exps)}",
        f"- total input duration: {fmt(total_input_duration, 2)} s ({fmt(total_input_duration / 60.0, 2)} min)",
        f"- total input frames: {total_input_frames}",
        f"- per_window total ViPE elapsed: {fmt(total_per, 2)} s",
        f"- clip_once total ViPE elapsed: {fmt(total_clip, 2)} s",
        f"- time saved by clip_once: {fmt(total_per - total_clip, 2)} s ({fmt(pct_change(total_per, total_clip), 2)}%)",
        "",
        "## Per Video",
        "",
        "| stem | duration s | frames | windows | per_window s | clip_once s | time saved % | ATE reduction % | RPE rot reduction % | axis ATE reduction % |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for e in exps:
        lines.append(
            f"| {e['stem']} | {fmt(e.get('input_duration_s'), 2)} | {e.get('input_frames') or ''} | {e['windows']} | {fmt(e['per_window_vipe_elapsed_s'], 2)} | "
            f"{fmt(e['clip_once_vipe_elapsed_s'], 2)} | {fmt(e['time_saved_pct'], 2)} | "
            f"{fmt(e['ate_rmse_sim3_reduction_pct'], 2)} | "
            f"{fmt(e['rpe_rot_deg_mean_sim3_reduction_pct'], 2)} | "
            f"{fmt(e['axis_ate_rmse_reduction_pct'], 2)} |"
        )
    lines.extend(["", "## Charts", ""])
    for image in images:
        rel = image.relative_to(path.parent)
        lines.append(f"![{image.stem}]({rel})")
        lines.append("")
    path.write_text("\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input-root", type=Path, default=Path("outputs/window_mode_compare"))
    parser.add_argument("--out-dir", type=Path, default=Path("outputs/window_mode_compare/_aggregate"))
    parser.add_argument("--gt-root", type=Path, default=Path("pose_demo/data"), help="Directory containing <stem>_aligned.mp4 for input duration totals")
    args = parser.parse_args()

    summary_paths = sorted(p for p in args.input_root.glob("*/summary.csv") if p.parent.name != "_aggregate")
    if not summary_paths:
        raise SystemExit(f"no summary.csv files found under {args.input_root}")

    all_rows: list[dict[str, Any]] = []
    experiments: list[dict[str, Any]] = []
    for summary_csv in summary_paths:
        rows = read_rows(summary_csv)
        all_rows.extend(rows)
        experiments.append(summarize_experiment(rows, args.gt_root))
    experiments.sort(key=lambda e: e["stem"])

    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_csv(args.out_dir / "all_windows.csv", all_rows)
    write_csv(args.out_dir / "per_video_summary.csv", experiments)

    images = [
        args.out_dir / "runtime_by_video.png",
        args.out_dir / "time_saved_pct_by_video.png",
        args.out_dir / "ate_sim3_by_video.png",
        args.out_dir / "ate_sim3_reduction_pct_by_video.png",
        args.out_dir / "rpe_rot_reduction_pct_by_video.png",
        args.out_dir / "axis_ate_reduction_pct_by_video.png",
    ]
    plot_time(experiments, images[0])
    plot_pct(experiments, "time_saved_pct", "Runtime improvement: clip_once vs per_window", images[1])
    plot_metric_values(experiments, "ate_rmse_sim3", "ATE Sim3 by video", images[2])
    plot_pct(experiments, "ate_rmse_sim3_reduction_pct", "ATE Sim3 reduction: clip_once vs per_window", images[3])
    plot_pct(experiments, "rpe_rot_deg_mean_sim3_reduction_pct", "RPE rot reduction: clip_once vs per_window", images[4])
    plot_pct(experiments, "axis_ate_rmse_reduction_pct", "Axis ATE reduction: clip_once vs per_window", images[5])

    write_markdown(args.out_dir / "aggregate_summary.md", experiments, images)
    print(f"[aggregate] read {len(summary_paths)} experiment summaries")
    print(f"[aggregate] wrote {args.out_dir / 'aggregate_summary.md'}")
    print(f"[aggregate] wrote {args.out_dir / 'per_video_summary.csv'}")
    print(f"[aggregate] wrote {args.out_dir / 'all_windows.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
